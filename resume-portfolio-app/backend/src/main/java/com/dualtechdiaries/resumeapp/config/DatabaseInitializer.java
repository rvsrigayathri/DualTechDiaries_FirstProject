package com.dualtechdiaries.resumeapp.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Ensures 'users' and 'profiles' tables exist and have required columns
 * across PostgreSQL and H2 databases without risking existing data.
 */
@Component
@Order(1)
public class DatabaseInitializer implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(DatabaseInitializer.class);

    private final JdbcTemplate jdbcTemplate;

    public DatabaseInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        // 1. Initialize users table
        try {
            log.info("Verifying 'users' database table existence...");
            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    full_name VARCHAR(255) NOT NULL,
                    email VARCHAR(255) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    reset_token VARCHAR(255),
                    reset_token_expiry TIMESTAMP,
                    created_at TIMESTAMP,
                    updated_at TIMESTAMP
                )
            """);
            log.info("Database table 'users' is verified.");
        } catch (Exception e) {
            log.warn("Notice checking 'users' table: {}", e.getMessage());
        }

        // 2. Initialize profiles table
        try {
            log.info("Verifying 'profiles' database table existence...");
            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS profiles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,
                    title VARCHAR(255),
                    full_name VARCHAR(255),
                    email VARCHAR(255),
                    desired_role VARCHAR(255),
                    target_template VARCHAR(255),
                    resume_json TEXT,
                    created_at TIMESTAMP,
                    updated_at TIMESTAMP
                )
            """);

            // In case table already existed without user_id or title, add columns safely
            try {
                jdbcTemplate.execute("ALTER TABLE profiles ADD COLUMN IF NOT EXISTS user_id BIGINT");
            } catch (Exception ignored) {}

            try {
                jdbcTemplate.execute("ALTER TABLE profiles ADD COLUMN IF NOT EXISTS title VARCHAR(255)");
            } catch (Exception ignored) {}

            log.info("Database table 'profiles' is verified with user association.");
        } catch (Exception e) {
            log.warn("Notice checking 'profiles' table: {}", e.getMessage());
        }
    }
}
