package com.dualtechdiaries.resumeapp.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Ensures the 'profiles' table exists across PostgreSQL and H2 databases.
 * Guarantees that the relation 'profiles' is ready even before initial API requests.
 */
@Component
@Order(1)
public class DatabaseInitializer implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(DatabaseInitializer.class);

    private final JdbcTemplate jdbcTemplate;

    public DatabaseInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        try {
            log.info("Verifying 'profiles' database table existence...");
            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS profiles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    full_name VARCHAR(255),
                    email VARCHAR(255),
                    desired_role VARCHAR(255),
                    target_template VARCHAR(255),
                    resume_json TEXT,
                    created_at TIMESTAMP,
                    updated_at TIMESTAMP
                )
            """);
            log.info("Database table 'profiles' is verified and ready.");
        } catch (Exception e) {
            log.warn("Table initialization check completed with notice: {}", e.getMessage());
        }
    }
}
